CREATE SCHEMA IF NOT EXISTS shared;
CREATE SCHEMA IF NOT EXISTS user_domain;
CREATE SCHEMA IF NOT EXISTS account_domain;
CREATE SCHEMA IF NOT EXISTS transaction_domain;

-- shared.currencies
CREATE TABLE shared.currencies (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(100) NOT NULL,
    iso_code        VARCHAR(3) NOT NULL,
    decimal_places  INT NOT NULL,
    CONSTRAINT uk_currency_name UNIQUE (name),
    CONSTRAINT uk_currency_iso_code UNIQUE (iso_code),
    CONSTRAINT chk_currency_decimal_places CHECK (decimal_places >= 0)
);

-- user_domain.countries
CREATE TABLE user_domain.countries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    name        VARCHAR(100) NOT NULL,
    iso_code    VARCHAR(3) NOT NULL,
    CONSTRAINT uk_country_name UNIQUE (name),
    CONSTRAINT uk_country_iso_code UNIQUE (iso_code)
);

-- user_domain.users
CREATE TABLE user_domain.users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    email_encrypted     VARCHAR(500) NOT NULL,
    email_lookup_hash   VARCHAR(64) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    role                VARCHAR(20) NOT NULL,
    status              VARCHAR(20) NOT NULL,
    CONSTRAINT uk_user_email_lookup_hash UNIQUE (email_lookup_hash)
);

-- user_domain.personal_data
CREATE TABLE user_domain.personal_data (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMPTZ NOT NULL,
    name                        VARCHAR(100) NOT NULL,
    surname                     VARCHAR(100) NOT NULL,
    phone                       VARCHAR(20),
    gender                      VARCHAR(10) NOT NULL,
    birthdate                   DATE NOT NULL,
    document_number_hash        VARCHAR(128) NOT NULL,
    document_number_encrypted   VARCHAR(500) NOT NULL,
    country_id                  BIGINT NOT NULL,
    personal_data_user_id       BIGINT NOT NULL,
    CONSTRAINT uk_document_country_number UNIQUE (country_id, document_number_hash),
    CONSTRAINT uk_personal_data_user UNIQUE (personal_data_user_id),
    CONSTRAINT fk_personal_document_country FOREIGN KEY (country_id) REFERENCES user_domain.countries (id),
    CONSTRAINT fk_personal_data_user FOREIGN KEY (personal_data_user_id) REFERENCES user_domain.users (id)
);

-- user_domain.user_preferences
CREATE TABLE user_domain.user_preferences (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    dark_mode       BOOLEAN NOT NULL,
    language_code   VARCHAR(2) NOT NULL,
    user_id         BIGINT NOT NULL,
    CONSTRAINT uk_user_preferences_user_id UNIQUE (user_id),
    CONSTRAINT fk_user_preference_user FOREIGN KEY (user_id) REFERENCES user_domain.users (id)
);

-- user_domain.addresses
CREATE TABLE user_domain.addresses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(100) NOT NULL,
    street          VARCHAR(100) NOT NULL,
    city            VARCHAR(100) NOT NULL,
    postal_code     VARCHAR(20),
    country_id      BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    CONSTRAINT uk_address_user UNIQUE (user_id),
    CONSTRAINT fk_address_country FOREIGN KEY (country_id) REFERENCES user_domain.countries (id),
    CONSTRAINT fk_address_user FOREIGN KEY (user_id) REFERENCES user_domain.users (id)
);

-- account_domain.accounts
CREATE TABLE account_domain.accounts (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMPTZ NOT NULL,
    user_id                     BIGINT NOT NULL,
    account_number_encrypted    VARCHAR(500) NOT NULL,
    account_number_hash         VARCHAR(128) NOT NULL,
    version                     BIGINT NOT NULL,
    balance                     NUMERIC(19,4) NOT NULL DEFAULT 0,
    currency_id                 BIGINT NOT NULL,
    account_type                VARCHAR(20) NOT NULL,
    status                      VARCHAR(10) NOT NULL,
    CONSTRAINT uk_account_account_number_hash UNIQUE (account_number_hash),
    CONSTRAINT chk_account_balance CHECK (balance >= 0),
    CONSTRAINT fk_account_user FOREIGN KEY (user_id) REFERENCES user_domain.users (id),
    CONSTRAINT fk_account_currency FOREIGN KEY (currency_id) REFERENCES shared.currencies (id)
);

-- transaction_domain.categories
CREATE TABLE transaction_domain.categories (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    accounting_type         VARCHAR(20) NOT NULL,
    category_owner_type     VARCHAR(255) NOT NULL,
    created_by              BIGINT,
    CONSTRAINT "uk_category_name_createdBy" UNIQUE (name, created_by, accounting_type),
    CONSTRAINT fk_category_created_by FOREIGN KEY (created_by) REFERENCES user_domain.users (id)
);

CREATE UNIQUE INDEX uk_category_system_name_accounting_type
    ON transaction_domain.categories (name, accounting_type)
    WHERE created_by IS NULL;

-- transaction_domain.transactions
CREATE TABLE transaction_domain.transactions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    reference_number        VARCHAR(100) NOT NULL,
    description             VARCHAR(200),
    user_id                 BIGINT NOT NULL,
    type                    VARCHAR(20) NOT NULL,
    status                  VARCHAR(20) NOT NULL,
    category_id             BIGINT NOT NULL,
    exchange_rate           NUMERIC(19,8) NOT NULL,
    exchange_rate_time      TIMESTAMPTZ NOT NULL,
    source_currency_id      BIGINT NOT NULL,
    target_currency_id      BIGINT NOT NULL,
    CONSTRAINT uk_transactions_reference_number UNIQUE (user_id, reference_number),
    CONSTRAINT chk_transaction_exchange_rate_consistency CHECK (
        (source_currency_id = target_currency_id AND exchange_rate = 1)
        OR
        (source_currency_id <> target_currency_id AND exchange_rate > 0)
    ),
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES user_domain.users (id),
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id) REFERENCES transaction_domain.categories (id),
    CONSTRAINT fk_transactions_source_currency FOREIGN KEY (source_currency_id) REFERENCES shared.currencies (id),
    CONSTRAINT fk_transactions_target_currency FOREIGN KEY (target_currency_id) REFERENCES shared.currencies (id)
);

-- transaction_domain.transaction_entries
CREATE TABLE transaction_domain.transaction_entries (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMPTZ NOT NULL,
    transaction_id               BIGINT NOT NULL,
    account_id                   BIGINT NOT NULL,
    transaction_entry_type       VARCHAR(20) NOT NULL,
    amount                       NUMERIC NOT NULL,
    currency_id                  BIGINT NOT NULL,
    description                  VARCHAR(100),
    CONSTRAINT chk_transaction_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT fk_transaction_entry_transaction FOREIGN KEY (transaction_id) REFERENCES transaction_domain.transactions (id),
    CONSTRAINT fk_transaction_entry_account FOREIGN KEY (account_id) REFERENCES account_domain.accounts (id),
    CONSTRAINT fk_transaction_entry_currency FOREIGN KEY (currency_id) REFERENCES shared.currencies (id)
);
